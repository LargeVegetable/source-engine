#!/usr/bin/env python3
# Generates the launcher's export table: every symbol imported by an engine
# module that no other module defines, i.e. what the launcher executable must
# provide from libc, libstdc++, libgcc, SDL2 and friends. The output is an
# assembly file so C++ mangled names can be referenced directly, and so the
# linker pulls exactly those objects out of the static libraries.
#
# usage: gen_exports.py <nm> <output.S> <module.so>...

import subprocess
import sys

def dynamic_symbols(nm, path):
	out = subprocess.run([nm, '-D', path], check=True, capture_output=True, text=True).stdout
	for line in out.splitlines():
		parts = line.split()
		if len(parts) == 2:   # undefined: "U name" / "w name"
			yield parts[0], parts[1]
		elif len(parts) == 3: # defined: "addr T name"
			yield parts[1], parts[2]

def main():
	nm, output, modules = sys.argv[1], sys.argv[2], sys.argv[3:]

	defined = set()
	imports = set()
	for path in modules:
		for kind, name in dynamic_symbols(nm, path):
			if kind in ('U', 'w', 'v'):
				imports.add(name)
			else:
				defined.add(name)

	# References are strong even for weak imports: a weak reference wouldn't
	# pull the definition out of a static library (e.g. __cxa_pure_virtual
	# from libsupc++), and anything genuinely missing should fail the link
	needed = sorted((n for n in imports if n not in defined), key=lambda n: n.encode())

	with open(output, 'w') as f:
		f.write('@ generated by gen_exports.py, do not edit\n')
		f.write('\t.syntax unified\n')

		f.write('\t.section .rodata.vita_export_names,"aMS",%progbits,1\n')
		for i, name in enumerate(needed):
			f.write('.Lname%d:\n\t.asciz "%s"\n' % (i, name))

		f.write('\t.section .data.rel.ro.vita_exports,"aw"\n')
		f.write('\t.align 2\n\t.global g_VitaExports\ng_VitaExports:\n')
		for i, name in enumerate(needed):
			f.write('\t.word .Lname%d, "%s"\n' % (i, name))

		f.write('\t.section .rodata.vita_export_count,"a"\n')
		f.write('\t.align 2\n\t.global g_VitaExportCount\ng_VitaExportCount:\n')
		f.write('\t.word %d\n' % len(needed))

	print('%d exports from %d modules' % (len(needed), len(modules)))

if __name__ == '__main__':
	main()
